CREATE OR REPLACE VIEW dw.vw_ventas_analiticas AS
SELECT
    f.venta_uuid,
    f.venta_detalle_uuid,
    df.fecha,
    dh.hora,
    dp.producto_uuid,
    dp.nombre AS producto,
    dp.tipo AS tipo_producto,
    dc.categoria_uuid,
    dc.nombre AS categoria,
    du.usuario_uuid,
    du.nombre AS usuario,
    f.cantidad,
    f.precio_unitario,
    f.importe_linea,
    f.descuento_linea,
    f.impuesto_linea,
    f.ingreso_neto_linea,
    f.costo_linea,
    f.utilidad_estimada,
    f.estado_venta,
    f.metodo_pago,
    f.mesa_numero
FROM dw.fact_ventas f
JOIN dw.dim_fecha df ON df.fecha_sk = f.fecha_sk
JOIN dw.dim_hora dh ON dh.hora_sk = f.hora_sk
JOIN dw.dim_producto dp ON dp.producto_sk = f.producto_sk
JOIN dw.dim_categoria dc ON dc.categoria_sk = f.categoria_sk
JOIN dw.dim_usuario du ON du.usuario_sk = f.usuario_sk
WHERE f.estado_venta = 'finalizada';

CREATE OR REPLACE VIEW dw.vw_ventas_diarias AS
SELECT
    df.fecha,
    dc.categoria_sk,
    dc.nombre AS categoria,
    SUM(f.cantidad) AS unidades_vendidas,
    COUNT(DISTINCT f.venta_uuid) AS transacciones,
    ROUND(SUM(f.ingreso_neto_linea), 2) AS ingresos,
    ROUND(SUM(f.costo_linea), 2) AS costos,
    ROUND(SUM(f.utilidad_estimada), 2) AS utilidad_estimada,
    ROUND(
        SUM(f.ingreso_neto_linea)
        / NULLIF(COUNT(DISTINCT f.venta_uuid), 0), 2
    ) AS ingreso_promedio_por_transaccion
FROM dw.fact_ventas f
JOIN dw.dim_fecha df ON df.fecha_sk = f.fecha_sk
JOIN dw.dim_categoria dc ON dc.categoria_sk = f.categoria_sk
WHERE f.estado_venta = 'finalizada'
GROUP BY df.fecha, dc.categoria_sk, dc.nombre;

CREATE OR REPLACE VIEW dw.vw_ventas_resumen_diario AS
SELECT
    df.fecha,
    SUM(f.cantidad) AS unidades_vendidas,
    COUNT(DISTINCT f.venta_uuid) AS transacciones,
    ROUND(SUM(f.ingreso_neto_linea), 2) AS ingresos,
    ROUND(SUM(f.costo_linea), 2) AS costos,
    ROUND(SUM(f.utilidad_estimada), 2) AS utilidad_estimada,
    ROUND(
        SUM(f.importe_linea - f.descuento_linea + f.impuesto_linea)
        / NULLIF(COUNT(DISTINCT f.venta_uuid), 0), 2
    ) AS ticket_promedio,
    ROUND(
        SUM(f.importe_linea - f.descuento_linea + f.impuesto_linea), 2
    ) AS total_cobrado
FROM dw.fact_ventas f
JOIN dw.dim_fecha df ON df.fecha_sk = f.fecha_sk
WHERE f.estado_venta = 'finalizada'
GROUP BY df.fecha;

