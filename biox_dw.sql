CREATE OR REPLACE VIEW meta.vw_kpi_cumplimiento AS
WITH base AS (
    SELECT
        s.kpi_id,
        k.codigo,
        k.nombre,
        k.descripcion,
        k.tipo,
        k.periodicidad,
        k.unidad,
        k.direccion,
        k.formula,
        k.fuente,
        k.responsable AS responsable_kpi,
        k.accion_correctiva AS accion_correctiva_kpi,
        s.anio_mes,
        s.categoria_uuid,
        CASE
            WHEN s.categoria_uuid IS NULL THEN 'Global'
            ELSE COALESCE(dc.nombre, s.categoria_uuid::text)
        END AS categoria,
        s.numerador,
        s.denominador,
        s.valor,
        m.valor_meta,
        m.umbral_amarillo_pct,
        COALESCE(m.responsable, k.responsable) AS responsable,
        COALESCE(m.accion_correctiva, k.accion_correctiva) AS accion_correctiva
    FROM dw.kpi_mensual s
    JOIN meta.kpi k ON k.kpi_id = s.kpi_id
    LEFT JOIN dw.dim_categoria dc
        ON dc.categoria_uuid = s.categoria_uuid
       AND dc.es_actual
    LEFT JOIN meta.kpi_meta m
        ON m.kpi_id = s.kpi_id
       AND m.anio_mes = s.anio_mes
       AND m.categoria_uuid IS NOT DISTINCT FROM s.categoria_uuid
    WHERE k.activo
),
porcentajes AS (
    SELECT
        base.*,
        CASE
            WHEN valor_meta IS NULL OR direccion = 'informativo' THEN NULL
            WHEN direccion = 'mayor' THEN
                CASE
                    WHEN valor_meta = 0 THEN 100::numeric
                    ELSE ROUND(100 * valor / NULLIF(valor_meta, 0), 2)
                END
            WHEN direccion = 'menor' THEN
                CASE
                    WHEN valor = 0 THEN 100::numeric
                    ELSE ROUND(100 * valor_meta / NULLIF(valor, 0), 2)
                END
        END AS cumplimiento_pct
    FROM base
)
SELECT
    porcentajes.*,
    CASE
        WHEN direccion = 'informativo' THEN 'informativo'
        WHEN valor_meta IS NULL THEN 'sin_meta'
        WHEN cumplimiento_pct >= 100 THEN 'cumplido'
        WHEN cumplimiento_pct >= COALESCE(umbral_amarillo_pct, 80) THEN 'atencion'
        ELSE 'critico'
    END AS estado_semaforo
FROM porcentajes;

