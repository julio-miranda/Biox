CREATE OR REPLACE VIEW dw.vw_kpi_consolidado AS
WITH ventas AS (
    SELECT
        date_trunc('month', df.fecha)::date AS anio_mes,
        dc.categoria_uuid,
        SUM(f.ingreso_neto_linea)::numeric AS ingresos,
        COUNT(DISTINCT f.venta_uuid)::numeric AS transacciones,
        SUM(f.importe_linea - f.descuento_linea + f.impuesto_linea)::numeric AS cobrado,
        SUM(f.cantidad)::numeric AS unidades
    FROM dw.fact_ventas f
    JOIN dw.dim_fecha df ON df.fecha_sk = f.fecha_sk
    JOIN dw.dim_categoria dc ON dc.categoria_sk = f.categoria_sk
    WHERE f.estado_venta = 'finalizada'
    GROUP BY GROUPING SETS (
        (date_trunc('month', df.fecha)::date),
        (date_trunc('month', df.fecha)::date, dc.categoria_uuid)
    )
),
indicadores_ventas AS (
    SELECT
        k.kpi_id,
        v.anio_mes,
        v.categoria_uuid,
        x.numerador,
        x.denominador,
        x.valor
    FROM ventas v
    CROSS JOIN LATERAL (
        VALUES
            ('ventas_ingresos_netos', v.ingresos, NULL::numeric, v.ingresos),
            ('ventas_transacciones', v.transacciones, NULL::numeric, v.transacciones),
            ('ventas_ticket_promedio', v.cobrado, v.transacciones,
                ROUND(v.cobrado / NULLIF(v.transacciones, 0), 2)),
            ('ventas_unidades', v.unidades, NULL::numeric, v.unidades)
    ) x(codigo, numerador, denominador, valor)
    JOIN meta.kpi k ON k.codigo = x.codigo AND k.activo
),
inventario AS (
    SELECT
        date_trunc('month', df.fecha)::date AS anio_mes,
        dc.categoria_uuid,
        COUNT(*)::numeric AS movimientos
    FROM dw.fact_inventario f
    JOIN dw.dim_fecha df ON df.fecha_sk = f.fecha_sk
    JOIN dw.dim_categoria dc ON dc.categoria_sk = f.categoria_sk
    GROUP BY GROUPING SETS (
        (date_trunc('month', df.fecha)::date),
        (date_trunc('month', df.fecha)::date, dc.categoria_uuid)
    )
),
indicadores_inventario AS (
    SELECT
        k.kpi_id, i.anio_mes, i.categoria_uuid,
        i.movimientos, NULL::numeric, i.movimientos
    FROM inventario i
    JOIN meta.kpi k
        ON k.codigo = 'inventario_movimientos' AND k.activo
),
afluencia AS (
    SELECT
        date_trunc('month', df.fecha)::date AS anio_mes,
        SUM(f.cantidad_entradas)::numeric AS entradas
    FROM dw.fact_afluencia f
    JOIN dw.dim_fecha df ON df.fecha_sk = f.fecha_sk
    GROUP BY date_trunc('month', df.fecha)::date
),
indicadores_afluencia AS (
    SELECT
        k.kpi_id, a.anio_mes, NULL::uuid,
        a.entradas, NULL::numeric, a.entradas
    FROM afluencia a
    JOIN meta.kpi k
        ON k.codigo = 'afluencia_entradas' AND k.activo
),
satisfaccion AS (
    SELECT
        date_trunc('month', df.fecha)::date AS anio_mes,
        SUM(f.calificacion_general)::numeric AS suma_calificaciones,
        COUNT(*)::numeric AS encuestas
    FROM dw.fact_satisfaccion f
    JOIN dw.dim_fecha df ON df.fecha_sk = f.fecha_sk
    GROUP BY date_trunc('month', df.fecha)::date
),
indicadores_satisfaccion AS (
    SELECT
        k.kpi_id, s.anio_mes, NULL::uuid,
        s.suma_calificaciones, s.encuestas,
        s.suma_calificaciones / NULLIF(s.encuestas, 0)
    FROM satisfaccion s
    JOIN meta.kpi k
        ON k.codigo = 'satisfaccion_promedio' AND k.activo
),
ultima_fotografia AS (
    SELECT DISTINCT ON (
        date_trunc('month', capturado_en AT TIME ZONE 'America/El_Salvador')::date
    )
        date_trunc('month', capturado_en AT TIME ZONE 'America/El_Salvador')::date AS anio_mes,
        run_uuid
    FROM dw.fact_existencias
    ORDER BY
        date_trunc('month', capturado_en AT TIME ZONE 'America/El_Salvador')::date,
        capturado_en DESC,
        run_uuid DESC
),
existencias AS (
    SELECT
        u.anio_mes,
        f.categoria_uuid,
        COUNT(*) FILTER (WHERE f.bajo_minimo)::numeric AS bajo_minimo
    FROM ultima_fotografia u
    JOIN dw.fact_existencias f ON f.run_uuid = u.run_uuid
    GROUP BY GROUPING SETS (
        (u.anio_mes),
        (u.anio_mes, f.categoria_uuid)
    )
),
indicadores_existencias AS (
    SELECT
        k.kpi_id, e.anio_mes, e.categoria_uuid,
        e.bajo_minimo, NULL::numeric, e.bajo_minimo
    FROM existencias e
    JOIN meta.kpi k
        ON k.codigo = 'inventario_productos_bajo_minimo' AND k.activo
)
SELECT * FROM indicadores_ventas
UNION ALL SELECT * FROM indicadores_inventario
UNION ALL SELECT * FROM indicadores_afluencia
UNION ALL SELECT * FROM indicadores_satisfaccion
UNION ALL SELECT * FROM indicadores_existencias;

