-- PROCEDIMIENTO DE TRANSFORMACIÓN Y CARGA
-- ============================================================

CREATE OR REPLACE PROCEDURE dw.transform_staging(p_run_uuid uuid)
LANGUAGE plpgsql
AS $$
DECLARE
    v_inicio timestamptz;
    v_esperadas bigint[];
    v_cargadas bigint[];
    v_origen numeric;
    v_destino numeric;
    v_kpis bigint;
BEGIN
    SELECT started_at
    INTO v_inicio
    FROM dw.etl_runs
    WHERE run_uuid = p_run_uuid
      AND estado = 'running'
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'No existe una ejecución ETL activa con id %.', p_run_uuid;
    END IF;

    -- Dimensión de fechas
    WITH fechas AS (
        SELECT DISTINCT
            (fecha_hora AT TIME ZONE 'America/El_Salvador')::date AS fecha
        FROM (
            SELECT created_at AS fecha_hora FROM stg.ventas
            UNION ALL SELECT created_at FROM stg.movimientos_stock
            UNION ALL SELECT created_at FROM stg.registros_afluencia
            UNION ALL SELECT created_at FROM stg.satisfaccion_encuestas
            UNION ALL SELECT capturado_en FROM stg.existencias_actuales
        ) t
    )
    INSERT INTO dw.dim_fecha (
        fecha, dia, mes, nombre_mes, trimestre, anio,
        dia_semana_iso, nombre_dia, semana_iso, es_fin_semana
    )
    SELECT
        fecha,
        EXTRACT(DAY FROM fecha)::smallint,
        EXTRACT(MONTH FROM fecha)::smallint,
        (ARRAY[
            'enero','febrero','marzo','abril','mayo','junio',
            'julio','agosto','septiembre','octubre','noviembre','diciembre'
        ])[EXTRACT(MONTH FROM fecha)::integer],
        EXTRACT(QUARTER FROM fecha)::smallint,
        EXTRACT(YEAR FROM fecha)::smallint,
        EXTRACT(ISODOW FROM fecha)::smallint,
        (ARRAY[
            'lunes','martes','miércoles','jueves','viernes','sábado','domingo'
        ])[EXTRACT(ISODOW FROM fecha)::integer],
        EXTRACT(WEEK FROM fecha)::smallint,
        EXTRACT(ISODOW FROM fecha)::integer IN (6,7)
    FROM fechas
    ON CONFLICT (fecha) DO NOTHING;

    -- Dimensión de horas: un registro por minuto del día
    INSERT INTO dw.dim_hora (
        minuto_dia, hora, hora_del_dia, minuto,
        intervalo_15_min, franja_horaria
    )
    SELECT
        m,
        make_time(m / 60, m % 60, 0),
        (m / 60)::smallint,
        (m % 60)::smallint,
        to_char(make_time((m - m % 15) / 60, (m - m % 15) % 60, 0), 'HH24:MI')
        || '-' ||
        to_char(make_time(LEAST((m - m % 15) + 14, 1439) / 60,
                          LEAST((m - m % 15) + 14, 1439) % 60, 0), 'HH24:MI'),
        CASE
            WHEN m / 60 < 6 THEN 'madrugada'
            WHEN m / 60 < 12 THEN 'mañana'
            WHEN m / 60 < 18 THEN 'tarde'
            ELSE 'noche'
        END
    FROM generate_series(0, 1439) AS m
    ON CONFLICT (minuto_dia) DO NOTHING;

    -- Dimensión de categorías: historial de cambios
    UPDATE dw.dim_categoria d
    SET es_actual = false, vigente_hasta = v_inicio
    FROM stg.categorias s
    WHERE d.categoria_uuid = s.source_uuid
      AND d.es_actual
      AND ROW(d.nombre, d.descripcion, d.activo)
          IS DISTINCT FROM ROW(s.nombre, s.descripcion, s.activo);

    INSERT INTO dw.dim_categoria (
        categoria_uuid, nombre, descripcion, activo,
        vigente_desde, vigente_hasta, es_actual
    )
    SELECT
        s.source_uuid, s.nombre, s.descripcion, s.activo,
        CASE WHEN EXISTS (
            SELECT 1 FROM dw.dim_categoria h
            WHERE h.categoria_uuid = s.source_uuid
        ) THEN v_inicio ELSE TIMESTAMPTZ '1900-01-01 00:00:00+00' END,
        NULL, true
    FROM stg.categorias s
    WHERE NOT EXISTS (
        SELECT 1 FROM dw.dim_categoria d
        WHERE d.categoria_uuid = s.source_uuid AND d.es_actual
    );

    -- Dimensión de usuarios
    UPDATE dw.dim_usuario d
    SET es_actual = false, vigente_hasta = v_inicio
    FROM stg.usuarios s
    WHERE d.usuario_uuid = s.source_uuid
      AND d.es_actual
      AND ROW(d.nombre, d.role, d.activo)
          IS DISTINCT FROM ROW(s.nombre, s.role, s.activo);

    INSERT INTO dw.dim_usuario (
        usuario_uuid, nombre, role, activo, es_desconocido,
        vigente_desde, vigente_hasta, es_actual
    )
    SELECT
        s.source_uuid, s.nombre, s.role, s.activo, false,
        CASE WHEN EXISTS (
            SELECT 1 FROM dw.dim_usuario h
            WHERE h.usuario_uuid = s.source_uuid
        ) THEN v_inicio ELSE TIMESTAMPTZ '1900-01-01 00:00:00+00' END,
        NULL, true
    FROM stg.usuarios s
    WHERE NOT EXISTS (
        SELECT 1 FROM dw.dim_usuario d
        WHERE d.usuario_uuid = s.source_uuid AND d.es_actual
    );

    -- Dimensión de productos
    UPDATE dw.dim_producto d
    SET es_actual = false, vigente_hasta = v_inicio
    FROM stg.productos s
    WHERE d.producto_uuid = s.source_uuid
      AND d.es_actual
      AND ROW(
          d.categoria_uuid, d.nombre, d.tipo, d.unidad_medida,
          d.precio, d.costo_promedio, d.stock_minimo, d.activo
      ) IS DISTINCT FROM ROW(
          s.categoria_uuid, s.nombre, s.tipo, s.unidad_medida,
          s.precio, s.costo_promedio, s.stock_minimo, s.activo
      );

    INSERT INTO dw.dim_producto (
        producto_uuid, categoria_uuid, nombre, tipo, unidad_medida,
        precio, costo_promedio, stock_minimo, activo,
        vigente_desde, vigente_hasta, es_actual
    )
    SELECT
        s.source_uuid, s.categoria_uuid, s.nombre, s.tipo, s.unidad_medida,
        s.precio, s.costo_promedio, s.stock_minimo, s.activo,
        CASE WHEN EXISTS (
            SELECT 1 FROM dw.dim_producto h
            WHERE h.producto_uuid = s.source_uuid
        ) THEN v_inicio ELSE TIMESTAMPTZ '1900-01-01 00:00:00+00' END,
        NULL, true
    FROM stg.productos s
    WHERE NOT EXISTS (
        SELECT 1 FROM dw.dim_producto d
        WHERE d.producto_uuid = s.source_uuid AND d.es_actual
    );

    -- Fotografía de existencias
    INSERT INTO dw.fact_existencias (
        run_uuid, producto_uuid, categoria_uuid,
        fecha_sk, hora_sk, producto_sk,
        stock_actual, stock_minimo, bajo_minimo,
        unidad_medida, capturado_en
    )
    SELECT
        p_run_uuid, s.source_uuid, s.categoria_uuid,
        df.fecha_sk, dh.hora_sk, dp.producto_sk,
        s.stock_actual, s.stock_minimo,
        s.stock_actual <= s.stock_minimo,
        s.unidad_medida, s.capturado_en
    FROM stg.existencias_actuales s
    JOIN dw.dim_fecha df
      ON df.fecha = (s.capturado_en AT TIME ZONE 'America/El_Salvador')::date
    JOIN dw.dim_hora dh
      ON dh.minuto_dia =
         EXTRACT(HOUR FROM (s.capturado_en AT TIME ZONE 'America/El_Salvador'))::integer * 60
         + EXTRACT(MINUTE FROM (s.capturado_en AT TIME ZONE 'America/El_Salvador'))::integer
    JOIN dw.dim_producto dp
      ON dp.producto_uuid = s.source_uuid
     AND s.capturado_en >= dp.vigente_desde
     AND (dp.vigente_hasta IS NULL OR s.capturado_en < dp.vigente_hasta)
    ON CONFLICT (run_uuid, producto_uuid) DO UPDATE SET
        categoria_uuid = EXCLUDED.categoria_uuid,
        fecha_sk = EXCLUDED.fecha_sk,
        hora_sk = EXCLUDED.hora_sk,
        producto_sk = EXCLUDED.producto_sk,
        stock_actual = EXCLUDED.stock_actual,
        stock_minimo = EXCLUDED.stock_minimo,
        bajo_minimo = EXCLUDED.bajo_minimo,
        unidad_medida = EXCLUDED.unidad_medida,
        capturado_en = EXCLUDED.capturado_en;

    -- Hechos de ventas
    WITH lineas AS (
        SELECT
            d.source_uuid AS venta_detalle_uuid,
            d.venta_uuid,
            d.producto_uuid,
            d.cantidad,
            d.precio_unitario,
            d.costo_unitario,
            d.total_linea,
            v.usuario_uuid,
            v.descuento,
            v.impuesto,
            v.estado AS estado_venta,
            v.metodo_pago,
            v.mesa_numero,
            v.created_at AS fecha_hora_operacion,
            SUM(d.total_linea) OVER (PARTITION BY d.venta_uuid) AS total_lineas,
            ROW_NUMBER() OVER (
                PARTITION BY d.venta_uuid
                ORDER BY d.created_at, d.source_uuid
            ) AS numero_linea,
            COUNT(*) OVER (PARTITION BY d.venta_uuid) AS cantidad_lineas
        FROM stg.venta_detalle d
        JOIN stg.ventas v ON v.source_uuid = d.venta_uuid
    ),
    bases AS (
        SELECT *,
            CASE WHEN total_lineas > 0
                THEN ROUND(descuento * total_linea / total_lineas, 2)
                ELSE 0 END AS descuento_base,
            CASE WHEN total_lineas > 0
                THEN ROUND(impuesto * total_linea / total_lineas, 2)
                ELSE 0 END AS impuesto_base
        FROM lineas
    ),
    valores AS (
        SELECT *,
            CASE
                WHEN total_lineas > 0 AND numero_linea = cantidad_lineas
                THEN descuento -
                    (SUM(descuento_base) OVER (PARTITION BY venta_uuid) - descuento_base)
                ELSE descuento_base
            END AS descuento_linea,
            CASE
                WHEN total_lineas > 0 AND numero_linea = cantidad_lineas
                THEN impuesto -
                    (SUM(impuesto_base) OVER (PARTITION BY venta_uuid) - impuesto_base)
                ELSE impuesto_base
            END AS impuesto_linea
        FROM bases
    ),
    resueltos AS (
        SELECT
            v.*,
            df.fecha_sk,
            dh.hora_sk,
            dp.producto_sk,
            dc.categoria_sk,
            du.usuario_sk,
            ROUND(v.cantidad * v.costo_unitario, 2) AS costo_linea,
            v.total_linea - v.descuento_linea AS ingreso_neto_linea
        FROM valores v
        JOIN dw.dim_fecha df
          ON df.fecha = (v.fecha_hora_operacion AT TIME ZONE 'America/El_Salvador')::date
        JOIN dw.dim_hora dh
          ON dh.minuto_dia =
             EXTRACT(HOUR FROM (v.fecha_hora_operacion AT TIME ZONE 'America/El_Salvador'))::integer * 60
             + EXTRACT(MINUTE FROM (v.fecha_hora_operacion AT TIME ZONE 'America/El_Salvador'))::integer
        JOIN dw.dim_producto dp
          ON dp.producto_uuid = v.producto_uuid
         AND v.fecha_hora_operacion >= dp.vigente_desde
         AND (dp.vigente_hasta IS NULL OR v.fecha_hora_operacion < dp.vigente_hasta)
        JOIN dw.dim_categoria dc
          ON dc.categoria_uuid = dp.categoria_uuid
         AND v.fecha_hora_operacion >= dc.vigente_desde
         AND (dc.vigente_hasta IS NULL OR v.fecha_hora_operacion < dc.vigente_hasta)
        JOIN dw.dim_usuario du
          ON du.usuario_uuid = v.usuario_uuid
         AND v.fecha_hora_operacion >= du.vigente_desde
         AND (du.vigente_hasta IS NULL OR v.fecha_hora_operacion < du.vigente_hasta)
    )
    INSERT INTO dw.fact_ventas (
        venta_detalle_uuid, venta_uuid, fecha_sk, hora_sk,
        producto_sk, categoria_sk, usuario_sk,
        cantidad, precio_unitario, costo_unitario,
        importe_linea, descuento_linea, impuesto_linea,
        ingreso_neto_linea, costo_linea, utilidad_estimada,
        estado_venta, metodo_pago, mesa_numero,
        fecha_hora_operacion, fecha_carga
    )
    SELECT
        venta_detalle_uuid, venta_uuid, fecha_sk, hora_sk,
        producto_sk, categoria_sk, usuario_sk,
        cantidad, precio_unitario, costo_unitario,
        total_linea, descuento_linea, impuesto_linea,
        ingreso_neto_linea, costo_linea,
        ingreso_neto_linea - costo_linea,
        estado_venta, metodo_pago, mesa_numero,
        fecha_hora_operacion, now()
    FROM resueltos
    ON CONFLICT (venta_detalle_uuid) DO UPDATE SET
        venta_uuid = EXCLUDED.venta_uuid,
        fecha_sk = EXCLUDED.fecha_sk,
        hora_sk = EXCLUDED.hora_sk,
        producto_sk = EXCLUDED.producto_sk,
        categoria_sk = EXCLUDED.categoria_sk,
        usuario_sk = EXCLUDED.usuario_sk,
        cantidad = EXCLUDED.cantidad,
        precio_unitario = EXCLUDED.precio_unitario,
        costo_unitario = EXCLUDED.costo_unitario,
        importe_linea = EXCLUDED.importe_linea,
        descuento_linea = EXCLUDED.descuento_linea,
        impuesto_linea = EXCLUDED.impuesto_linea,
        ingreso_neto_linea = EXCLUDED.ingreso_neto_linea,
        costo_linea = EXCLUDED.costo_linea,
        utilidad_estimada = EXCLUDED.utilidad_estimada,
        estado_venta = EXCLUDED.estado_venta,
        metodo_pago = EXCLUDED.metodo_pago,
        mesa_numero = EXCLUDED.mesa_numero,
        fecha_hora_operacion = EXCLUDED.fecha_hora_operacion,
        fecha_carga = now();

    -- Hechos de inventario
    WITH resueltos AS (
        SELECT
            m.*,
            df.fecha_sk,
            dh.hora_sk,
            dp.producto_sk,
            dc.categoria_sk,
            COALESCE(du.usuario_sk, 0) AS usuario_sk,
            CASE
                WHEN m.tipo IN ('entrada', 'ajuste_entrada', 'devolucion')
                    THEN m.cantidad
                WHEN m.tipo IN ('salida', 'ajuste_salida', 'consumo_receta')
                    THEN -m.cantidad
                ELSE 0
            END AS cantidad_firmada,
            p.unidad_medida AS unidad_producto
        FROM stg.movimientos_stock m
        JOIN stg.productos p ON p.source_uuid = m.producto_uuid
        JOIN dw.dim_fecha df
          ON df.fecha = (m.created_at AT TIME ZONE 'America/El_Salvador')::date
        JOIN dw.dim_hora dh
          ON dh.minuto_dia =
             EXTRACT(HOUR FROM (m.created_at AT TIME ZONE 'America/El_Salvador'))::integer * 60
             + EXTRACT(MINUTE FROM (m.created_at AT TIME ZONE 'America/El_Salvador'))::integer
        JOIN dw.dim_producto dp
          ON dp.producto_uuid = m.producto_uuid
         AND m.created_at >= dp.vigente_desde
         AND (dp.vigente_hasta IS NULL OR m.created_at < dp.vigente_hasta)
        JOIN dw.dim_categoria dc
          ON dc.categoria_uuid = dp.categoria_uuid
         AND m.created_at >= dc.vigente_desde
         AND (dc.vigente_hasta IS NULL OR m.created_at < dc.vigente_hasta)
        LEFT JOIN dw.dim_usuario du
          ON du.usuario_uuid = m.usuario_uuid
         AND m.created_at >= du.vigente_desde
         AND (du.vigente_hasta IS NULL OR m.created_at < du.vigente_hasta)
    )
    INSERT INTO dw.fact_inventario (
        movimiento_uuid, fecha_sk, hora_sk, producto_sk, categoria_sk,
        usuario_sk, tipo_movimiento, cantidad_movimiento, cantidad_firmada,
        unidad_medida, costo_unitario, proveedor_uuid, venta_uuid,
        envase_uuid, reversa_de_uuid, observacion,
        fecha_hora_operacion, fecha_carga
    )
    SELECT
        source_uuid, fecha_sk, hora_sk, producto_sk, categoria_sk,
        usuario_sk, tipo, cantidad, cantidad_firmada,
        COALESCE(unidad_medida, unidad_producto), costo,
        proveedor_uuid, venta_uuid, envase_uuid, reversa_de_uuid,
        observacion, created_at, now()
    FROM resueltos
    ON CONFLICT (movimiento_uuid) DO UPDATE SET
        fecha_sk = EXCLUDED.fecha_sk,
        hora_sk = EXCLUDED.hora_sk,
        producto_sk = EXCLUDED.producto_sk,
        categoria_sk = EXCLUDED.categoria_sk,
        usuario_sk = EXCLUDED.usuario_sk,
        tipo_movimiento = EXCLUDED.tipo_movimiento,
        cantidad_movimiento = EXCLUDED.cantidad_movimiento,
        cantidad_firmada = EXCLUDED.cantidad_firmada,
        unidad_medida = EXCLUDED.unidad_medida,
        costo_unitario = EXCLUDED.costo_unitario,
        proveedor_uuid = EXCLUDED.proveedor_uuid,
        venta_uuid = EXCLUDED.venta_uuid,
        envase_uuid = EXCLUDED.envase_uuid,
        reversa_de_uuid = EXCLUDED.reversa_de_uuid,
        observacion = EXCLUDED.observacion,
        fecha_hora_operacion = EXCLUDED.fecha_hora_operacion,
        fecha_carga = now();

    -- Hechos de afluencia
    WITH resueltos AS (
        SELECT
            a.*,
            df.fecha_sk,
            dh.hora_sk,
            COALESCE(du.usuario_sk, 0) AS usuario_sk
        FROM stg.registros_afluencia a
        JOIN dw.dim_fecha df
          ON df.fecha = (a.created_at AT TIME ZONE 'America/El_Salvador')::date
        JOIN dw.dim_hora dh
          ON dh.minuto_dia =
             EXTRACT(HOUR FROM (a.created_at AT TIME ZONE 'America/El_Salvador'))::integer * 60
             + EXTRACT(MINUTE FROM (a.created_at AT TIME ZONE 'America/El_Salvador'))::integer
        LEFT JOIN dw.dim_usuario du
          ON du.usuario_uuid = a.usuario_uuid
         AND a.created_at >= du.vigente_desde
         AND (du.vigente_hasta IS NULL OR a.created_at < du.vigente_hasta)
    )
    INSERT INTO dw.fact_afluencia (
        registro_afluencia_uuid, fecha_sk, hora_sk, usuario_sk,
        tipo_movimiento, cantidad_movimiento, cantidad_entradas,
        cantidad_salidas, observacion, fecha_hora_operacion, fecha_carga
    )
    SELECT
        source_uuid, fecha_sk, hora_sk, usuario_sk,
        tipo_movimiento, cantidad,
        CASE WHEN tipo_movimiento = 'entrada' THEN cantidad ELSE 0 END,
        CASE WHEN tipo_movimiento = 'salida' THEN cantidad ELSE 0 END,
        observacion, created_at, now()
    FROM resueltos
    ON CONFLICT (registro_afluencia_uuid) DO UPDATE SET
        fecha_sk = EXCLUDED.fecha_sk,
        hora_sk = EXCLUDED.hora_sk,
        usuario_sk = EXCLUDED.usuario_sk,
        tipo_movimiento = EXCLUDED.tipo_movimiento,
        cantidad_movimiento = EXCLUDED.cantidad_movimiento,
        cantidad_entradas = EXCLUDED.cantidad_entradas,
        cantidad_salidas = EXCLUDED.cantidad_salidas,
        observacion = EXCLUDED.observacion,
        fecha_hora_operacion = EXCLUDED.fecha_hora_operacion,
        fecha_carga = now();

    -- Hechos de satisfacción
    WITH encuestas AS (
        SELECT e.*, v.usuario_uuid
        FROM stg.satisfaccion_encuestas e
        LEFT JOIN stg.ventas v ON v.source_uuid = e.venta_uuid
    ),
    resueltos AS (
        SELECT
            e.*,
            df.fecha_sk,
            dh.hora_sk,
            COALESCE(du.usuario_sk, 0) AS usuario_sk
        FROM encuestas e
        JOIN dw.dim_fecha df
          ON df.fecha = (e.created_at AT TIME ZONE 'America/El_Salvador')::date
        JOIN dw.dim_hora dh
          ON dh.minuto_dia =
             EXTRACT(HOUR FROM (e.created_at AT TIME ZONE 'America/El_Salvador'))::integer * 60
             + EXTRACT(MINUTE FROM (e.created_at AT TIME ZONE 'America/El_Salvador'))::integer
        LEFT JOIN dw.dim_usuario du
          ON du.usuario_uuid = e.usuario_uuid
         AND e.created_at >= du.vigente_desde
         AND (du.vigente_hasta IS NULL OR e.created_at < du.vigente_hasta)
    )
    INSERT INTO dw.fact_satisfaccion (
        encuesta_uuid, fecha_sk, hora_sk, usuario_sk, venta_uuid,
        mesa_numero, calificacion_general, ambiente, musica, atencion,
        seguridad, limpieza, tiempo_espera, recomendacion, canal,
        comentario, fecha_hora_operacion, fecha_carga
    )
    SELECT
        source_uuid, fecha_sk, hora_sk, usuario_sk, venta_uuid,
        mesa_numero, calificacion_general, ambiente, musica, atencion,
        seguridad, limpieza, tiempo_espera, recomendacion, canal,
        comentario, created_at, now()
    FROM resueltos
    ON CONFLICT (encuesta_uuid) DO UPDATE SET
        fecha_sk = EXCLUDED.fecha_sk,
        hora_sk = EXCLUDED.hora_sk,
        usuario_sk = EXCLUDED.usuario_sk,
        venta_uuid = EXCLUDED.venta_uuid,
        mesa_numero = EXCLUDED.mesa_numero,
        calificacion_general = EXCLUDED.calificacion_general,
        ambiente = EXCLUDED.ambiente,
        musica = EXCLUDED.musica,
        atencion = EXCLUDED.atencion,
        seguridad = EXCLUDED.seguridad,
        limpieza = EXCLUDED.limpieza,
        tiempo_espera = EXCLUDED.tiempo_espera,
        recomendacion = EXCLUDED.recomendacion,
        canal = EXCLUDED.canal,
        comentario = EXCLUDED.comentario,
        fecha_hora_operacion = EXCLUDED.fecha_hora_operacion,
        fecha_carga = now();

    -- Validación de cantidades cargadas
    SELECT ARRAY[
        (SELECT COUNT(*) FROM stg.venta_detalle),
        (SELECT COUNT(*) FROM stg.movimientos_stock),
        (SELECT COUNT(*) FROM stg.registros_afluencia),
        (SELECT COUNT(*) FROM stg.satisfaccion_encuestas),
        (SELECT COUNT(*) FROM stg.existencias_actuales)
    ] INTO v_esperadas;

    SELECT ARRAY[
        (SELECT COUNT(*) FROM stg.venta_detalle s
         JOIN dw.fact_ventas f ON f.venta_detalle_uuid = s.source_uuid),
        (SELECT COUNT(*) FROM stg.movimientos_stock s
         JOIN dw.fact_inventario f ON f.movimiento_uuid = s.source_uuid),
        (SELECT COUNT(*) FROM stg.registros_afluencia s
         JOIN dw.fact_afluencia f ON f.registro_afluencia_uuid = s.source_uuid),
        (SELECT COUNT(*) FROM stg.satisfaccion_encuestas s
         JOIN dw.fact_satisfaccion f ON f.encuesta_uuid = s.source_uuid),
        (SELECT COUNT(*) FROM stg.existencias_actuales s
         JOIN dw.fact_existencias f
           ON f.run_uuid = p_run_uuid AND f.producto_uuid = s.source_uuid)
    ] INTO v_cargadas;

    IF v_esperadas IS DISTINCT FROM v_cargadas THEN
        RAISE EXCEPTION
            'Validación de carga fallida. Filas esperadas: %, filas cargadas: %.',
            v_esperadas, v_cargadas;
    END IF;

    -- Reconciliación de importes de ventas
    SELECT COALESCE(SUM(total_linea), 0)
    INTO v_origen
    FROM stg.venta_detalle;

    SELECT COALESCE(SUM(f.importe_linea), 0)
    INTO v_destino
    FROM dw.fact_ventas f
    JOIN stg.venta_detalle s
      ON s.source_uuid = f.venta_detalle_uuid;

    IF v_origen IS DISTINCT FROM v_destino THEN
        RAISE EXCEPTION
            'Diferencia en importes de ventas. Origen: %, DW: %.',
            v_origen, v_destino;
    END IF;

    -- Reconciliación de inventario
    SELECT COALESCE(SUM(cantidad), 0)
    INTO v_origen
    FROM stg.movimientos_stock;

    SELECT COALESCE(SUM(f.cantidad_movimiento), 0)
    INTO v_destino
    FROM dw.fact_inventario f
    JOIN stg.movimientos_stock s
      ON s.source_uuid = f.movimiento_uuid;

    IF v_origen IS DISTINCT FROM v_destino THEN
        RAISE EXCEPTION
            'Diferencia en cantidades de inventario. Origen: %, DW: %.',
            v_origen, v_destino;
    END IF;

    -- Reconciliación de afluencia
    SELECT COALESCE(SUM(cantidad), 0)
    INTO v_origen
    FROM stg.registros_afluencia;

    SELECT COALESCE(SUM(cantidad_movimiento), 0)
    INTO v_destino
    FROM dw.fact_afluencia f
    JOIN stg.registros_afluencia s
      ON s.source_uuid = f.registro_afluencia_uuid;

    IF v_origen IS DISTINCT FROM v_destino THEN
        RAISE EXCEPTION
            'Diferencia en registros de afluencia. Origen: %, DW: %.',
            v_origen, v_destino;
    END IF;

    -- Reconciliación de satisfacción
    SELECT COALESCE(SUM(calificacion_general), 0)
    INTO v_origen
    FROM stg.satisfaccion_encuestas;

    SELECT COALESCE(SUM(f.calificacion_general), 0)
    INTO v_destino
    FROM dw.fact_satisfaccion f
    JOIN stg.satisfaccion_encuestas s
      ON s.source_uuid = f.encuesta_uuid;

    IF v_origen IS DISTINCT FROM v_destino THEN
        RAISE EXCEPTION
            'Diferencia en calificaciones de satisfacción. Origen: %, DW: %.',
            v_origen, v_destino;
    END IF;

    -- Reconciliación de existencias
    SELECT COALESCE(SUM(stock_actual), 0)
    INTO v_origen
    FROM stg.existencias_actuales;

    SELECT COALESCE(SUM(stock_actual), 0)
    INTO v_destino
    FROM dw.fact_existencias
    WHERE run_uuid = p_run_uuid;

    IF v_origen IS DISTINCT FROM v_destino THEN
        RAISE EXCEPTION
            'Diferencia en existencias. Origen: %, DW: %.',
            v_origen, v_destino;
    END IF;

    -- Actualización de indicadores mensuales
    MERGE INTO dw.kpi_mensual d
    USING dw.vw_kpi_consolidado s
       ON d.kpi_id = s.kpi_id
      AND d.anio_mes = s.anio_mes
      AND d.categoria_uuid IS NOT DISTINCT FROM s.categoria_uuid
    WHEN MATCHED AND ROW(d.numerador, d.denominador, d.valor)
        IS DISTINCT FROM ROW(s.numerador, s.denominador, s.valor)
    THEN UPDATE SET
        numerador = s.numerador,
        denominador = s.denominador,
        valor = s.valor,
        calculado_en = now(),
        run_uuid = p_run_uuid
    WHEN NOT MATCHED THEN
        INSERT (
            kpi_id, anio_mes, categoria_uuid,
            numerador, denominador, valor, calculado_en, run_uuid
        )
        VALUES (
            s.kpi_id, s.anio_mes, s.categoria_uuid,
            s.numerador, s.denominador, s.valor, now(), p_run_uuid
        );

    GET DIAGNOSTICS v_kpis = ROW_COUNT;

    UPDATE dw.etl_runs
    SET
        finished_at = now(),
        estado = 'success',
        filas_validadas = jsonb_build_object(
            'fact_ventas', v_cargadas[1],
            'fact_inventario', v_cargadas[2],
            'fact_afluencia', v_cargadas[3],
            'fact_satisfaccion', v_cargadas[4],
            'fact_existencias', v_cargadas[5],
            'kpi_mensual', v_kpis
        ),
        error = NULL
    WHERE run_uuid = p_run_uuid;
END;
$$;

